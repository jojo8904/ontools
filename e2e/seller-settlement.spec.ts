import { expect, test } from '@playwright/test'

test('isolated seller settlement demo, mapping, local CSV and export', async ({ page }, testInfo) => {
  await page.route(/googletagmanager|googlesyndication|doubleclick|kakao|daumcdn|google-analytics/, route => route.abort())
  const startupErrors: string[] = []
  page.on('console', message => { if (message.type() === 'error') startupErrors.push(message.text()) })
  page.on('pageerror', error => startupErrors.push(error.message))
  await page.goto('/seller-settlement')
  await expect(page.getByRole('heading', { name: '판매자 정산 비교', exact: true })).toBeVisible()
  const iframe = page.locator('iframe[title="개인정보 격리 정산 비교 작업 공간"]')
  await expect(iframe).toHaveAttribute('sandbox', 'allow-scripts allow-downloads')
  const frame = page.frameLocator('iframe[title="개인정보 격리 정산 비교 작업 공간"]')
  try { await expect(frame.getByRole('button', { name: '선택한 열 비교하기' })).toBeDisabled() }
  catch (error) { console.error('Workspace startup:', startupErrors, page.frames().map(f => f.url())); throw error }
  await frame.getByRole('button', { name: '합성 예제로 시작' }).click()
  await frame.getByRole('button', { name: '선택한 열 비교하기' }).click()
  await expect(frame.getByRole('status')).toHaveText('7개 비교 항목 · 2개 일치')
  await expect(frame.getByRole('cell', { name: '-300.00', exact: true })).toBeVisible()
  await expect(frame.getByRole('region', { name: '비교 결과' }).getByRole('cell', { name: '12345678901234567890', exact: true })).toBeVisible()
  await frame.getByLabel('상태 필터').selectOption('중복 키')
  await expect(frame.getByRole('cell', { name: 'DUP', exact: true })).toBeVisible()
  const downloadPromise = page.waitForEvent('download')
  await frame.getByRole('button', { name: '전체 결과 CSV 다운로드' }).click()
  expect((await downloadPromise).suggestedFilename()).toBe('settlement-comparison.csv')
  await frame.getByLabel('상태 필터').selectOption('전체')
  await page.screenshot({ path: testInfo.outputPath('seller-settlement-demo.png'), fullPage: true })
  const f = page.frames().find(f => f.url().includes('seller-settlement-workspace'))!
  expect(await f.evaluate(() => { try { return parent.document.body.textContent } catch { return 'isolated' } })).toBe('isolated')
  expect(await page.evaluate(() => { try { return document.querySelector('iframe')!.contentWindow!.document.body.textContent } catch { return 'isolated' } })).toBe('isolated')
  expect(await f.evaluate(() => { try { localStorage.setItem('probe', 'test'); return 'accessible' } catch { return 'blocked' } })).toBe('blocked')
  const network: string[] = []
  page.on('request', r => { if (r.frame() === f) network.push(r.url()) })
  await frame.getByRole('button', { name: '초기화', exact: true }).click()
  await frame.getByLabel('주문 파일', { exact: true }).setInputFiles({ name: 'private-orders.csv', mimeType: 'text/csv', buffer: Buffer.from('id,n\n00123,100\n=CMD(),1') })
  await expect(frame.getByLabel('주문 키 열', { exact: true })).toBeVisible()
  await frame.getByLabel('정산 파일', { exact: true }).setInputFiles({ name: 'private-settlements.csv', mimeType: 'text/csv', buffer: Buffer.from('id,n\n00123,90\n=CMD(),1') })
  await frame.getByRole('button', { name: '선택한 열 비교하기' }).click()
  await expect(frame.getByRole('status')).toHaveText('2개 비교 항목 · 1개 일치')
  await expect(frame.getByRole('cell', { name: '-10.00', exact: true })).toBeVisible()
  await frame.getByLabel('주문 금액 열').selectOption('0')
  await expect(frame.getByRole('status')).toHaveCount(0)
  await frame.getByRole('button', { name: '선택한 열 비교하기' }).click()
  await expect(frame.getByRole('alert')).toContainText('서로 다른')
  expect(network).toEqual([])
  expect(page.url()).not.toContain('private')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('workspace bypasses ad-bearing layout and prevents outbound connections', async ({ request }) => {
  const response = await request.get('/seller-settlement-workspace')
  expect(response.status()).toBe(200)
  expect(response.headers()['content-security-policy']).toContain("connect-src 'none'")
  expect(response.headers()['content-security-policy']).toContain('sandbox allow-scripts allow-downloads')
  expect(response.headers()['x-robots-tag']).toContain('noindex')
  expect(await response.text()).not.toMatch(/googletagmanager|googlesyndication|dataLayer|gtag|adfit/i)
})
