import { expect, test } from '@playwright/test'

test('car quotes compare locally with deposit, coverage, variable payments and term guards', async ({ page }, testInfo) => {
  await page.route(/googletagmanager|googlesyndication|doubleclick|kakao|daumcdn|google-analytics/, route => route.abort())
  const requests: string[] = []
  await page.goto('/car-cost')
  page.on('request', request => { if (request.method() !== 'GET') requests.push(request.url()) })
  const purchase = page.getByRole('group', { name: '구매 견적', exact: true })
  const lease = page.getByRole('group', { name: '리스 견적', exact: true })
  await expect(page.getByText('보험·세금·정비 포함 여부가 미확인입니다.', { exact: false })).toBeVisible()
  await purchase.getByLabel('계약 시 차량 납부액·초기 부대비용 (원)').fill('30000000')
  await purchase.getByLabel('기간 종료 시 차량 매각 예상가 (원)').fill('18000000')
  await lease.getByLabel('반환 보증금 (원)').fill('5000000')
  await lease.getByLabel('소멸 선납금 (원)').fill('3000000')
  await lease.getByLabel('월 납부액 (원)', { exact: true }).fill('400000')
  await page.getByRole('button', { name: '총비용 비교하기' }).click()
  const results = page.getByRole('region', { name: '비교 결과' })
  await expect(results.getByText('잔존가치 반영 총비용 12,000,000원', { exact: true })).toBeVisible()
  await expect(results.getByText('잔존가치 반영 총비용 17,400,000원', { exact: true })).toBeVisible()
  await lease.getByLabel('만기 시나리오').selectOption('buyout')
  await expect(results).toHaveCount(0)
  await lease.getByLabel('보증금 차감 전 인수대금 (원)').fill('18000000')
  await lease.getByLabel('기간 종료 시 차량 매각 예상가 (원)').fill('17000000')
  await lease.getByLabel('별도 연 보험료 (원)').fill('1200000')
  await lease.getByLabel('보험료 포함 여부').selectOption('included')
  await lease.getByLabel('변동 납부: 기간 납부총액 직접 입력').check()
  await lease.getByLabel('기간 납부총액 (월 납부액 대신 적용, 원)').fill('14000000')
  await page.getByRole('button', { name: '총비용 비교하기' }).click()
  await expect(results.getByText('잔존가치 반영 총비용 18,000,000원', { exact: true })).toBeVisible()
  await lease.getByLabel('견적 기간 (개월)').fill('48')
  await expect(page.getByRole('button', { name: '총비용 비교하기' })).toBeDisabled()
  await expect(page.getByText('견적 기간이 다릅니다.', { exact: false })).toBeVisible()
  await lease.getByLabel('견적 기간 (개월)').fill('36')
  await lease.getByLabel('연간 주행거리 (km)').fill('20000')
  await expect(page.getByText('연간 주행조건이 다릅니다.', { exact: false })).toBeVisible()
  await lease.getByLabel('월 납부액 (원)', { exact: true }).fill('-1')
  await expect(page.getByRole('button', { name: '총비용 비교하기' })).toBeDisabled()
  await lease.getByLabel('월 납부액 (원)', { exact: true }).fill('400000')
  await page.getByRole('button', { name: '총비용 비교하기' }).click()
  await expect(page.locator('link[rel="canonical"]')).toHaveAttribute('href', 'https://ontools.co.kr/car-cost')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(requests).toEqual([])
  await page.screenshot({ path: testInfo.outputPath('car-cost.png'), fullPage: true })
})
