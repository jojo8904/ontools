import { expect, test } from '@playwright/test'

test('travel internet quotes: repeat, edits, invalid inputs, reset and conditions', async ({ page }, testInfo) => {
  await page.route(/googletagmanager|googlesyndication|doubleclick|kakao|daumcdn|google-analytics/, route => route.abort())
  await page.goto('/travel-internet')
  const requests: string[] = []
  page.on('request', r => { if (r.method() !== 'GET') requests.push(r.url()) })
  const compare = page.getByRole('button', { name: '여행 전체 비용 비교하기' })
  const results = page.getByRole('region', { name: '비교 결과' })
  await expect(compare).toBeDisabled()
  await page.getByRole('button', { name: '합성 예제 넣기' }).click()
  await compare.click()
  await expect(results.getByText('입력 기준 총비용 24,000원', { exact: true })).toBeVisible()
  await expect(results.getByText('입력 기준 총비용 40,000원', { exact: true })).toBeVisible()
  await expect(results.getByText('입력 기준 총비용 20,000원', { exact: true })).toBeVisible()
  await compare.click()
  await expect(results.getByRole('article')).toHaveCount(3)
  const esim = page.getByRole('group', { name: 'eSIM 요금', exact: true })
  await esim.getByLabel('패키지 유효기간 (일)').fill('2')
  await expect(results).toHaveCount(0)
  await compare.click()
  await expect(results.getByText('패키지 유효기간이 여행보다 짧습니다.', { exact: false })).toBeVisible()
  const wifi = page.getByRole('group', { name: '포켓와이파이 요금', exact: true })
  await wifi.getByLabel('실제 요금 적용 일수 (일)').fill('6')
  await wifi.getByLabel('공용 기기 수 (대)').fill('2')
  await compare.click()
  await expect(results.getByText('입력 기준 총비용 41,000원', { exact: true })).toBeVisible()
  await expect(results.getByText('과금 일수와 여행 일수가 다릅니다.', { exact: false })).toBeVisible()
  for (const value of ['', '-1', '0.5', '100000001']) {
    await esim.getByLabel('1인당 패키지 총액 (원)').fill(value)
    await expect(compare).toBeDisabled()
    await expect(results).toHaveCount(0)
  }
  await esim.getByLabel('1인당 패키지 총액 (원)').fill('0')
  await expect(compare).toBeEnabled()
  await page.getByLabel('여행 인원 (명)').fill('0')
  await expect(compare).toBeDisabled()
  await page.getByLabel('여행 인원 (명)').fill('3')
  await wifi.getByLabel('공용 기기 수 (대)').fill('1')
  await compare.click()
  await expect(results.getByText('기기 수 × 기기당 사용 인원이', { exact: false })).toBeVisible()
  await expect(page.locator('link[rel="canonical"]')).toHaveAttribute('href', 'https://ontools.co.kr/travel-internet')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('travel-internet.png'), fullPage: true })
  await page.getByRole('button', { name: '초기화', exact: true }).click()
  await expect(compare).toBeDisabled()
  await expect(results).toHaveCount(0)
  await expect(page.getByLabel('여행 인원 (명)')).toHaveValue('2')
  await expect(esim.getByLabel('1인당 패키지 총액 (원)')).toBeEmpty()
  expect(requests).toEqual([])
})
